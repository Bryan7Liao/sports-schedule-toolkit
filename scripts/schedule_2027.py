games = {}
for line in raw.strip().splitlines():
    d, rest = line.split(' ', 1)
    games[d] = games[rest[1:]] if rest.startswith('=') else [tuple(g.split('@')) for g in rest.split()]

def todate(s):
    m, d = map(int, s.split('/')); return date(2027, m, d)

rows = []
for d, gs in games.items():
    for a, h in gs:
        rows.append((todate(d), a, h))
rows.sort(key=lambda r: r[0])

if __name__ == '__main__':
    print('total', len(rows))
    for half, cond in (('H1', lambda r: r[0] < date(2027, 7, 1)), ('H2', lambda r: r[0] >= date(2027, 7, 1))):
        rr = [r for r in rows if cond(r)]
        print(half, len(rr), 'home', Counter(r[2] for r in rr), 'away', Counter(r[1] for r in rr))
        print(' pairs', sorted(Counter(frozenset(r[1:]) for r in rr).values()))
        print(' H/A by pair', sorted(Counter((r[1], r[2]) for r in rr).items()))
